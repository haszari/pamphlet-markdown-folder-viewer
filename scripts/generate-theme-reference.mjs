import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readFile, writeFile } from "node:fs/promises";
import vm from "node:vm";

const require = createRequire(import.meta.url);
const ts = require("../renderer/node_modules/typescript");

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");

const paths = {
  swiftTokens: path.join(repoRoot, "Pamphlet/Models/ThemeTokens.swift"),
  themeHooks: path.join(repoRoot, "renderer/src/themeHooks.ts"),
  referenceData: path.join(repoRoot, "scripts/theme-reference-data.ts"),
  output: path.join(repoRoot, "docs/theme-reference.pamphlet.css"),
};

const [tokens, hooksModule, dataModule] = await Promise.all([
  readSwiftThemeTokens(paths.swiftTokens),
  loadTypeScriptModule(paths.themeHooks),
  loadTypeScriptModule(paths.referenceData),
]);

const css = generateReferenceCSS({
  tokens,
  rendererThemeHooks: hooksModule.rendererThemeHooks,
  data: dataModule.themeReferenceData,
});

await writeFile(paths.output, `${css.trimEnd()}\n`);

async function readSwiftThemeTokens(filePath) {
  const source = await readFile(filePath, "utf8");
  const tokens = [
    ...source.matchAll(/case\s+\w+\s*=\s*"(--pamphlet-[^"]+)"/g),
  ].map((match) => match[1]);
  if (tokens.length === 0) {
    throw new Error(`No ThemeToken values found in ${filePath}`);
  }
  return tokens;
}

async function loadTypeScriptModule(filePath) {
  const source = await readFile(filePath, "utf8");
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: filePath,
  }).outputText;

  const module = { exports: {} };
  vm.runInNewContext(
    transpiled,
    {
      exports: module.exports,
      module,
      require,
    },
    {
      filename: filePath,
    },
  );
  return module.exports;
}

function generateReferenceCSS({ tokens, rendererThemeHooks, data }) {
  const lines = [];
  lines.push("/*");
  lines.push("Pamphlet theme reference");
  lines.push("");
  lines.push("Generated by scripts/generate-theme-reference.mjs.");
  lines.push("Do not edit this file by hand.");
  lines.push("");
  lines.push(
    "Copy this file into a workspace as .pamphlet.css, or into a user theme folder as theme.css, then keep the parts you need.",
  );
  lines.push(
    "Theme tokens must be flat values. Do not use var(), @import, colour functions, or aliases in --pamphlet-* values.",
  );
  lines.push("Use macOS Font Book to find installed font family names.");
  lines.push("");
  lines.push("Authoritative docs:");
  for (const link of data.links) {
    lines.push(`- ${link.label}: ${link.url}`);
  }
  lines.push("*/");
  lines.push("");

  lines.push("/* Sanctioned Pamphlet variables");
  lines.push(
    "   Pamphlet reads these --pamphlet-* variables for app-recognised theme settings.",
  );
  lines.push(
    "   Colours in this section use hex values. Length examples prefer rem.",
  );
  lines.push("*/");
  lines.push(":root {");
  for (const token of tokens) {
    const description =
      data.tokenDescriptions[token] ?? "Pamphlet theme value.";
    const example = data.tokenExamples[token] ?? "initial";
    lines.push(`  /* ${description} */`);
    lines.push(`  ${token}: ${example};`);
  }
  lines.push("}");
  lines.push("");
  lines.push(
    "/* Adaptive themes can override flat token values for dark mode.",
  );
  lines.push(
    "   Docs: https://developer.mozilla.org/en-US/docs/Web/CSS/Reference/At-rules/@media/prefers-color-scheme",
  );
  lines.push("*/");
  lines.push("@media (prefers-color-scheme: dark) {");
  lines.push("  :root {");
  lines.push("    --pamphlet-background: #1f2328;");
  lines.push("    --pamphlet-foreground: #f6f8fa;");
  lines.push("    --pamphlet-accent: #7cb7ff;");
  lines.push("  }");
  lines.push("}");
  lines.push("");

  lines.push("/* Renderer-owned hooks");
  lines.push("   These classes are Pamphlet's public renderer hooks.");
  lines.push(
    "   Docs: https://developer.mozilla.org/en-US/docs/Web/CSS/CSS_selectors",
  );
  lines.push("*/");
  for (const hook of rendererThemeHooks) {
    lines.push(`/* ${hook.name}: ${hook.description} */`);
    lines.push(`${hook.selector} {`);
    lines.push("}");
    lines.push("");
  }

  for (const group of data.inheritedHookGroups) {
    lines.push(`/* ${group.title}`);
    lines.push(`   ${group.description}`);
    for (const link of group.links) {
      lines.push(`   Docs: ${link.url}`);
    }
    lines.push("*/");
    for (const hook of group.hooks) {
      lines.push(`/* ${hook.concept}: ${hook.description} */`);
      lines.push(`${hook.selectors.join(",\n")} {`);
      lines.push("}");
      lines.push("");
    }
  }

  return lines.join("\n");
}
